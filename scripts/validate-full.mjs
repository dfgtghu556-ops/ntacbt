const SUBJECTS = ["Physics", "Chemistry", "Mathematics"];
const TYPES = ["mcq", "integer"];
const TAGS = ["concept", "formula", "calculation", "misread", "silly", "guessed"];

function genQuestion(rng, i) {
  const subj = SUBJECTS[Math.floor(rng() * 3)];
  const type = rng() < 0.7 ? "mcq" : "integer";
  const q = {
    id: `q${i}`,
    no: i + 1,
    subject: subj,
    chapter: `Chapter ${Math.floor(rng() * 8) + 1}`,
    topic: `Topic ${Math.floor(rng() * 4) + 1}`,
    type,
    text: `Question ${i + 1} about physics/maths`,
    options: [],
    answer:
      type === "mcq"
        ? ["a", "b", "c", "d"][Math.floor(rng() * 4)]
        : String(Math.floor(rng() * 101)),
  };
  if (type === "mcq") {
    q.options = ["a", "b", "c", "d"].map((label) => ({ label, text: `Opt ${label}` }));
  } else if (rng() < 0.2) {
    q.accept = { kind: "range", lo: 40, hi: 60 };
    q.answer = "50";
  }
  if (rng() < 0.3) q.tag = TAGS[Math.floor(rng() * TAGS.length)];
  if (rng() < 0.5) q.sol = "Solution explanation here";
  return q;
}

function genTest(rng, n) {
  const questions = Array.from({ length: n }, (_, i) => genQuestion(rng, i));
  return {
    id: `test-${Math.floor(rng() * 1e6)}`,
    name: "Generated Test",
    createdAt: Date.now(),
    durationSec: 180 * 60,
    questions,
  };
}

function genResponses(rng, test, skipRate) {
  const responses = {};
  for (const q of test.questions) {
    const r = rng();
    if (r < skipRate) {
      responses[q.id] = { ans: null, time: Math.floor(rng() * 300) };
    } else {
      // mix correct / wrong
      const correct = rng() < 0.55;
      responses[q.id] = {
        ans: correct
          ? q.answer
          : q.type === "mcq"
            ? ["a", "b", "c", "d"].filter((x) => x !== q.answer)[Math.floor(rng() * 3)]
            : String(Number(q.answer) + 7),
        time: Math.floor(rng() * 400),
      };
    }
  }
  return responses;
}

function genPyqRows(rng, count) {
  const rows = [];
  const papers = [
    "jee-main-2024-online-27th-january-morning-shift",
    "jee-main-2025-online-22nd-january-evening-shift",
    "aieee-2013",
  ];
  for (let i = 0; i < count; i++) {
    const paperId = papers[Math.floor(rng() * papers.length)];
    const mcq = rng() < 0.7;
    rows.push({
      paper_id: paperId,
      subject: ["physics", "chemistry", "maths"][Math.floor(rng() * 3)],
      question: `PYQ question ${i} text with math`,
      question_type: mcq ? "mcq" : "integer",
      options: JSON.stringify(
        ["a", "b", "c", "d"].map((label) => ({ identifier: label, content: `Opt ${label}` })),
      ),
      correct_option: JSON.stringify(["a", "b", "c", "d"][Math.floor(rng() * 4)]),
      answer: mcq ? "" : Math.floor(rng() * 100).toString(),
      explanation: `Solution for ${i}`,
      chapter: `Chapter ${Math.floor(rng() * 10) + 1}`,
      topic: `Topic ${Math.floor(rng() * 5) + 1}`,
    });
  }
  return rows;
}

