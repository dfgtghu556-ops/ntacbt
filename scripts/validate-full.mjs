/* ------------------------------------------------------------------ */
/* Seeded deterministic RNG (LCG)                                     */
/* ------------------------------------------------------------------ */
function makeRng(seed) {
  let s = seed >>> 0;
  return () => {
    s = (Math.imul(s, 1664525) + 1013904223) >>> 0;
    return s / 2 ** 32;
  };
}

