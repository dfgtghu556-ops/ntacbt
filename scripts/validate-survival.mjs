async function main() {
  await buildBundle();
  const { DataStore } = P.store;
  const { computeSurvival, computeDualLane, weakTopicsInline } = P.survival;
  const { computeReadiness } = P.readiness;
  const { buildMicroDrill } = P.microDrill;
  const { mistakeFromStore } = P.mistake;
  const { computeHumaneStreak, emptyStreakStore } = P.streak;
  const { focusStreak, todayFocusSeconds } = P.focus;
  const { predictRank } = P.predict;

  section("Survival score — empty store");
  {
    const store = new DataStore({ ...emptyRaw(), aiPlanner: null });
    const s = computeSurvival(store);
    ok(typeof s.score === "number" && s.score >= 0 && s.score <= 100, "score in 0..100");
    ok(["on-track", "watch", "at-risk"].includes(s.status), "status is one of the buckets");
    ok(s.components.length === 5, "5 explainable components");
    ok(typeof s.nextAction === "string" && s.nextAction.length > 0, "has one executable next action");
    const sum = s.components.reduce((n, c) => n + c.contribution, 0);
    ok(Math.abs(sum - 1) < 1e-9, "component contributions sum to 1");
  }

  section("Survival score — student with evidence");
  {
    const raw = emptyRaw();
    const test = {
      id: "t1", name: "T1", createdAt: Date.now(), duration: 60,
      questions: [
        { id: "q1", subject: "Physics", chapter: "Electrostatics", topic: "Coulomb", type: "mcq", text: "What is k long formula?", options: [{label:"A",text:""},{label:"B",text:""}], answer: "b", accept: undefined },
        { id: "q2", subject: "Physics", chapter: "Electrostatics", topic: "Coulomb", type: "mcq", text: "Find value of field integral", options: [{label:"A",text:""},{label:"B",text:""}], answer: "b", accept: undefined },
        { id: "q3", subject: "Physics", chapter: "Electrostatics", topic: "Coulomb", type: "mcq", text: "Which of the following is NOT true about field?", options: [{label:"A",text:""},{label:"B",text:""}], answer: "a", accept: undefined },
      ],
    };
    raw.tests = [test];
    raw.attempts = [{
      id: "a1", testId: "t1", submittedAt: Date.now(), startedAt: Date.now() - 10000, timeTaken: 60,
      responses: {
        q1: { ans: "b", status: "answered", time: 30, changes: 0 },
        q2: { ans: "b", status: "answered", time: 30, changes: 0 },
        q3: { ans: "b", status: "answered", time: 30, changes: 0 },
      },
      result: { all: { correct: 2, wrong: 1, skipped: 0, marks: 7, neg: -1, time: 60, total: 3, max: 12, accuracy: 66.7 } },
    }];
    raw.aiPlanner = {
      profile: { target: "jeemain", language: "en", depth: "standard", speed: 1.25, dailyMin: 120, weekdayMin: 120, startDate: "2025-01-01", days: 30 },
      tasks: [
        { id: "p1", subject: "Physics", chapter: "Electrostatics", topic: "Coulomb", kind: "learn", date: "2025-01-01", estMin: 60, status: "done" },
        { id: "p2", subject: "Physics", chapter: "Electrostatics", topic: "Gauss", kind: "practice", date: "2025-01-01", estMin: 60, status: "todo" },
      ],
    };
    const store = new DataStore(raw);
    const rs = computeReadiness(store);
    ok(rs.attempts === 1, "readiness sees 1 attempt");
    ok(rs.weakTopics.length >= 1, "weak topic surfaced (1 of 2 wrong on Coulomb)");
    const s = computeSurvival(store, { streakDays: 3, focusMinutesToday: 40 });
    ok(s.score >= 0 && s.score <= 100, "score in range with evidence");
    ok(s.components.some((c) => c.key === "mistake"), "mistake component present");
    ok(s.components.every((c) => typeof c.how === "string" && c.how.length > 0), "every component has a how");

    const d = computeDualLane(store, rs);
    ok(typeof d.jee.score === "number" && typeof d.board.score === "number", "dual lane scores are numbers");
    ok(typeof d.split === "string" && d.split.length > 0, "dual lane split recommendation present");
  }

  section("Mistake DNA + micro-drill");
  {
    const raw = emptyRaw();
    const test = {
      id: "t1", name: "T1", createdAt: Date.now(), duration: 60,
      questions: [
        { id: "q1", subject: "Physics", chapter: "Electrostatics", topic: "Coulomb", type: "mcq", text: "Which of the following is NOT true about Coulomb's law?", options: [{label:"A",text:""},{label:"B",text:""}], answer: "a", accept: undefined },
        { id: "q2", subject: "Physics", chapter: "Electrostatics", topic: "Coulomb", type: "mcq", text: "Which statement is NOT correct regarding field lines?", options: [{label:"A",text:""},{label:"B",text:""}], answer: "b", accept: undefined },
        { id: "q3", subject: "Physics", chapter: "Electrostatics", topic: "Coulomb", type: "mcq", text: "All of the following are false about divergence EXCEPT", options: [{label:"A",text:""},{label:"B",text:""}], answer: "a", accept: undefined },
        { id: "q4", subject: "Physics", chapter: "Electrostatics", topic: "Coulomb", type: "mcq", text: "Which of the following is NOT a property?", options: [{label:"A",text:""},{label:"B",text:""}], answer: "b", accept: undefined },
      ],
    };
    raw.tests = [test];
    // All four wrong with "NOT" stems -> misread cluster strong.
    raw.attempts = [{
      id: "a1", testId: "t1", submittedAt: Date.now(), startedAt: Date.now() - 10000, timeTaken: 60,
      responses: Object.fromEntries(test.questions.map((q) => [q.id, { ans: q.text.includes("NOT") ? "a" : "b", status: "answered", time: 30, changes: 0 }])),
      result: { all: { correct: 0, wrong: 4, skipped: 0, marks: -4, neg: 0, time: 60, total: 4, max: 16, accuracy: 0 } },
    }];
    const store = new DataStore(raw);
    const mistake = mistakeFromStore(store);
    ok(mistake !== null, "a mistake pattern is derived from 4 wrong answers");
    ok(mistake.tag === "misread", "misread tag dominates (NOT-stems)");
    const rs = computeReadiness(store);
    const cards = buildMicroDrill({ weak: rs.weakTopics, mistake });
    ok(cards.length >= 1, "micro-drill returns cards");
    ok(cards.length >= 5, "micro-drill returns ~5 cards");
    ok(cards.every((c) => typeof c.prompt === "string" && c.prompt.length > 0 && typeof c.answer === "string" && c.answer.length > 0), "every card has prompt+answer");
    ok(cards.every((c) => c.recallType.length > 0), "every card has a recall type");
  }

  section("Rank / College predictor");
  {
    // A high score → high percentile, low rank, strong tier; honest, never zero.
    const strong = predictRank({ marks: 250, maxMarks: 300, accuracy: 90, weakTopics: [] });
    ok(strong.percentile > 99, "250/300 → >99 percentile");
    ok(strong.rank < 20000, "top marks → low AIR");
    ok(strong.tier.length > 0 && /IIT|zone|branch/i.test(strong.tier), "strong tier named");
    ok(typeof strong.expectation === "string" && strong.expectation.length > 0, "honest expectation present");
    ok(typeof strong.topFix === "string" && strong.topFix.length > 0, "top fix present");
    ok(strong.basis.includes("estimate"), "clearly labelled as an estimate (no fake guarantee)");

    // A genuinely low score → low percentile but still a plan (never a dead-end).
    // (NTA table: 15/300 ≈ 20.6%ile, 20/300 ≈ 37.7%ile.)
    const low = predictRank({ marks: 15, maxMarks: 300, accuracy: 30, weakTopics: [{ subject: "Physics", chapter: "Electrostatics" }] });
    ok(low.percentile < 50, "low marks → low percentile");
    ok(low.topFix.includes("Physics"), "low score fix targets the weak subject");
    ok(low.expectation.length > 0, "low score still gets an actionable, non-shaming message");

    // Target-aware tiering.
    const adv = predictRank({ marks: 200, maxMarks: 300, target: "jeeadv" });
    ok(adv.tier.length > 0, "jeeadv target returns a tier");
  }

  section("Humane streak + freeze");
  {
    const now = Date.now();
    const active = new Set();
    const d = (n) => {
      const dd = new Date(now - n * 24 * 3600 * 1000);
      return `${dd.getFullYear()}-${String(dd.getMonth() + 1).padStart(2, "0")}-${String(dd.getDate()).padStart(2, "0")}`;
    };
    active.add(d(0)); active.add(d(1)); active.add(d(2));
    const h = computeHumaneStreak(active, now, { store: emptyStreakStore() });
    ok(h.days >= 3, "3-day streak from active days");
    ok(h.atRiskToday === false, "not at risk when today is active");
    ok(typeof h.microWin === "string" && h.microWin.length > 0, "micro-win suggestion present");

    // Missed today, active yesterday -> at risk + freeze available
    const risky = computeHumaneStreak(new Set([d(1), d(2), d(3)]), now, { store: { ...emptyStreakStore(), days: 3, lastActive: d(1) } });
    ok(risky.atRiskToday === true, "at risk when today not active but streak on the line");
    ok(risky.freezesLeft >= 1, "freezes available");
    ok(typeof risky.nudge === "string" && risky.nudge.length > 0, "loss-framing nudge present (ethical)");
  }

  console.log("\n============================================================");
  if (failed === 0) {
    console.log(`Passed: ${passed}  Failed: 0`);
    console.log("All survival/mission/drill/streak checks green ✅");
  } else {
    console.log(`Passed: ${passed}  Failed: ${failed}`);
    console.log("Failures:");
    failures.forEach((f) => console.log("  ✗ " + f));
    process.exitCode = 1;
  }
}

main().catch((e) => {
  console.error("FATAL:", e);
  process.exitCode = 1;
});
