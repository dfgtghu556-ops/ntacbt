#!/usr/bin/env node
/**
 * VALIDATE SURVIVAL / MISSION-CONTROL / MICRO-DRILL / HUMANE-STREAK.
 *
 * Bundles the real production modules (survival, microDrill, mistake, streak,
 * readiness, focus, store, analytics) and runs functional assertions against
 * synthetic student stores. Exits non-zero on any failure (CI-friendly).
 */

import { build } from "rolldown";
import { mkdtemp, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const SRC = join(ROOT, "src");

let passed = 0;
let failed = 0;
const failures = [];
function ok(cond, label) {
  if (cond) passed++;
  else {
    failed++;
    failures.push(label);
    console.error("  ✗ " + label);
  }
}
function section(title) {
  console.log("\n=== " + title + " ===");
}

const entryPath = join(tmpdir(), `ntacbt-survival-entry-${process.pid}.ts`);
function buildEntry() {
  const lines = ["// @generated by scripts/validate-survival.mjs"];
  lines.push(`export * as survival from ${JSON.stringify(join(SRC, "features", "readiness", "survival"))};`);
  lines.push(`export * as readiness from ${JSON.stringify(join(SRC, "features", "readiness", "readiness"))};`);
  lines.push(`export * as predict from ${JSON.stringify(join(SRC, "features", "readiness", "predict"))};`);
  lines.push(`export * as microDrill from ${JSON.stringify(join(SRC, "features", "cbt", "microDrill"))};`);
  lines.push(`export * as mistake from ${JSON.stringify(join(SRC, "features", "cbt", "mistake"))};`);
  lines.push(`export * as analytics from ${JSON.stringify(join(SRC, "features", "cbt", "analytics"))};`);
  lines.push(`export * as streak from ${JSON.stringify(join(SRC, "features", "focus", "streak"))};`);
  lines.push(`export * as focus from ${JSON.stringify(join(SRC, "features", "focus", "focus"))};`);
  lines.push(`export * as store from ${JSON.stringify(join(SRC, "lib", "store"))};`);
  return lines.join("\n");
}

let P;
async function buildBundle() {
  await writeFile(entryPath, buildEntry(), "utf8");
  const out = join(tmpdir(), `ntacbt-survival-bundle-${process.pid}.mjs`);
  const res = await build({
    input: entryPath,
    output: { file: out, format: "esm" },
  });
  await import(pathToFileURL(out).href).then((m) => {
    P = m;
  });
}

function emptyRaw() {
  return {
    attempts: [],
    tests: [],
    settings: {},
    dailyQuestions: {},
    reviewSchedule: {},
    qtags: {},
    aiPlanner: null,
    plannerDone: {},
  };
}

