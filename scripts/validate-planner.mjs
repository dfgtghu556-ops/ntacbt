/* ------------------------------------------------------------------ */
/* Tiny test framework                                                */
/* ------------------------------------------------------------------ */
let passed = 0;
let failed = 0;
const failures = [];
const stats = { scenarios: 0, curatedEmpty: 0, fallbackEmpty: 0, throws: 0 };

function ok(cond, label) {
  if (cond) {
    passed++;
  } else {
    failed++;
    failures.push(label);
    console.error("  ✗ " + label);
  }
}
function section(title) {
  console.log("\n=== " + title + " ===");
}

/* ------------------------------------------------------------------ */
/* Build the bundle                                                    */
/* ------------------------------------------------------------------ */
const entryPath = join(tmpdir(), `ntacbt-planner-entry-${process.pid}.ts`);

// Build a correct entry with explicit paths
function buildEntry() {
  const lines = ["// @generated by scripts/validate-planner.mjs"];
  lines.push(
    `export * as normalize from ${JSON.stringify(join(SRC, "features", "planner", "normalize"))};`,
  );
  lines.push(
    `export * as engine from ${JSON.stringify(join(SRC, "features", "planner", "engine"))};`,
  );
  lines.push(
    `export * as adapt from ${JSON.stringify(join(SRC, "features", "planner", "adapt"))};`,
  );
  lines.push(
    `export * as readiness from ${JSON.stringify(join(SRC, "features", "readiness", "readiness"))};`,
  );
  lines.push(`export * as store from ${JSON.stringify(join(SRC, "lib", "store"))};`);
  lines.push(`export * as video from ${JSON.stringify(join(SRC, "data", "video-engine"))};`);
  lines.push(`export * as teachers from ${JSON.stringify(join(SRC, "data", "teachers"))};`);
  lines.push(`export * as syllabus from ${JSON.stringify(join(SRC, "data", "syllabus"))};`);
  lines.push(
    `export * as catalog from ${JSON.stringify(join(SRC, "features", "studytube", "catalog"))};`,
  );
  return lines.join("\n");
}

let P;
async function buildBundle() {
  await writeFile(entryPath, buildEntry(), "utf8");
  const out = join(tmpdir(), `ntacbt-planner-bundle-${process.pid}.mjs`);
  const res = await build({
    input: entryPath,
    output: { file: out, format: "esm" },
    resolve: { tsconfigFilename: join(ROOT, "tsconfig.json") },
    platform: "node",
  });
  if (!res || !res.output) throw new Error("Rolldown produced no output");
  P = await import(pathToFileURL(out).href);
  return out;
}

/* ------------------------------------------------------------------ */
/* Corpus generation                                                   */
/* ------------------------------------------------------------------ */
function flatSyllabusTopics() {
  const out = [];
  const subjects = P.syllabus.JEE_MAIN_2026_SYLLABUS.subjects || [];
  for (const subj of subjects) {
    for (const ch of subj.chapters || []) {
      const topics = ch.topics && ch.topics.length ? ch.topics.map((t) => t.name) : [ch.name];
      for (const topic of topics) out.push({ topic, subject: ch.subject || subj.name });
    }
  }
  return out;
}

