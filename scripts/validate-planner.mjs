#!/usr/bin/env node
/**
 * VALIDATE AI PLANNER — full-corpus + adversarial robustness harness.
 *
 * Bundles the *real* planner source (normalize, engine, adapt, readiness,
 * store, video-engine, teachers, syllabus) with Rolldown and runs the actual
 * production functions against:
 *
 *  1. A large generated corpus: every official syllabus topic × subject ×
 *     kind × depth × target × language (+ teacher/institute preferences),
 *     plus every legacy topic. This "training set" exercises the full
 *     decision surface so the planner must never crash or return malformed
 *     recommendations in any real combination.
 *  2. Ranking invariants on fabricated live YouTube candidates.
 *  3. Adversarial / malformed request payloads (null, arrays, objects, huge
 *     strings, NaN, unknown enums, unicode, whitespace-only, stopword topics).
 *  4. Readiness + adaptive-plan invariants on synthetic student stores.
 *
 * Exits non-zero on any failed assertion (CI-friendly). No network is used;
 * the recommendation engine's search function is stubbed.
 */

