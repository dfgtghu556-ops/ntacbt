/** Lookup helpers */
export function getTeachersByInstitute(instituteId: string): TeacherRecord[] {
  return TEACHERS.filter((t) => t.instituteId === instituteId);
}

export function getTeachersBySubject(
  subject: "Physics" | "Chemistry" | "Mathematics",
  instituteId?: string,
): TeacherRecord[] {
  return TEACHERS.filter((t) => {
    if (t.subject !== subject) return false;
    if (instituteId && t.instituteId !== instituteId) return false;
    return true;
  });
}

/**
 * Filter teachers by Institute, Subject, and Exam Target
 * If examTarget is "jeemain", it returns JEE Main faculties for that institute & subject.
 * If examTarget is "jeeadv", it returns JEE Advanced faculties.
 * If examTarget is "board12" or "cbse27", it returns Class 12 / Board faculties.
 */
export function getTopFaculties(
  instituteId?: string,
  subject?: "Physics" | "Chemistry" | "Mathematics",
  examTarget?: string,
): TeacherRecord[] {
  let list = TEACHERS.slice();
  if (instituteId && instituteId !== "all" && instituteId !== "auto") {
    list = list.filter((t) => t.instituteId === instituteId);
  }
  if (subject) {
    list = list.filter((t) => t.subject === subject);
  }
  if (examTarget && examTarget !== "all") {
    const norm = examTarget.toLowerCase();
    list = list.filter((t) => {
      if (norm === "jeemain" || norm === "jee-main") {
        return t.examTarget.includes("jeemain");
      }
      if (norm === "jeeadv" || norm === "jee-advanced") {
        return t.examTarget.includes("jeeadv");
      }
      if (norm === "board12" || norm === "cbse27" || norm === "cbse" || norm === "board") {
        return t.examTarget.includes("board12") || t.examTarget.includes("cbse27");
      }
      if (norm === "board11") {
        return t.examTarget.includes("board11");
      }
      return true;
    });
  }
  return list;
}

export function findTeacherById(id: string): TeacherRecord | undefined {
  return TEACHERS.find((t) => t.id === id);
}

export function findInstituteById(id: string): InstituteRecord | undefined {
  return INSTITUTES.find((i) => i.id === id);
}
